/** Local-date helpers. Booking dates are stored as YYYY-MM-DD in the visitor's local time. */
export function toISODate(d: Date): string {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
}

export function addDays(base: Date, days: number): Date {
  const d = new Date(base.getFullYear(), base.getMonth(), base.getDate());
  d.setDate(d.getDate() + days);
  return d;
}

export function fromISODate(iso: string): Date {
  const [y, m, d] = iso.split('-').map(Number);
  return new Date(y, m - 1, d);
}

/** Relative date from "today", used for all seeded sample data so dates never go stale. */
export function relativeISO(days: number, now = new Date()): string {
  return toISODate(addDays(now, days));
}
